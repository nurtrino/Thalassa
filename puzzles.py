# ── tetromino sigil fill (Talos-Principle style) ─────────────────────────────
TETROMINOES = {
    "I": [(0, 0), (1, 0), (2, 0), (3, 0)],
    "O": [(0, 0), (1, 0), (0, 1), (1, 1)],
    "T": [(0, 0), (1, 0), (2, 0), (1, 1)],
    "S": [(1, 0), (2, 0), (0, 1), (1, 1)],
    "Z": [(0, 0), (1, 0), (1, 1), (2, 1)],
    "L": [(0, 0), (0, 1), (0, 2), (1, 2)],
    "J": [(1, 0), (1, 1), (1, 2), (0, 2)],
}


def _normalize(cells) -> tuple:
    xs = min(x for x, y in cells)
    ys = min(y for x, y in cells)
    return tuple(sorted((x - xs, y - ys) for x, y in cells))


def _rotations(shape) -> list[tuple]:
    out, cur = [], list(shape)
    for _ in range(4):
        cur = [(y, -x) for x, y in cur]
        n = _normalize(cur)
        if n not in out:
            out.append(n)
    return out

ROTATIONS = {name: _rotations(shape) for name, shape in TETROMINOES.items()}


def gen_tetromino(rng: random.Random, w: int = 4, h: int = 4) -> dict:
    """Tile the region (rotations allowed while GENERATING), then hand each
    piece to the player in exactly the orientation it was placed."""
    grid = [-1] * (w * h)
    forms: list[tuple] = []                 # normalized form of each placed piece

    def fit(form, x0, y0):
        cells = []
        for dx, dy in form:
            x, y = x0 + dx, y0 + dy
            if not (0 <= x < w and 0 <= y < h) or grid[y * w + x] != -1:
                return None
            cells.append((x, y))
        return cells

    def solve() -> bool:
        try:
            i = grid.index(-1)
        except ValueError:
            return True
        y0, x0 = divmod(i, w)
        names = list(ROTATIONS)
        rng.shuffle(names)
        for name in names:
            for form in ROTATIONS[name]:
                for ax, ay in form:
                    cells = fit([(dx - ax, dy - ay) for dx, dy in form], x0, y0)
                    if cells:
                        idx = len(forms)
                        for x, y in cells:
                            grid[y * w + x] = idx
                        forms.append(_normalize(cells))
                        if solve():
                            return True
                        for x, y in cells:
                            grid[y * w + x] = -1
                        forms.pop()
        return False

    solve()
    order = list(range(len(forms)))
    rng.shuffle(order)
    pieces = [[list(c) for c in forms[i]] for i in order]
    return {"w": w, "h": h, "pieces": pieces, "secret": {}}


def check_tetromino(data: dict, assignment) -> bool:
    w, h, pieces = data["w"], data["h"], data["pieces"]
    if not isinstance(assignment, list) or len(assignment) != w * h:
        return False
    groups: dict[int, list] = {}
    for i, v in enumerate(assignment):
        if not isinstance(v, int) or not 0 <= v < len(pieces):
            return False
        groups.setdefault(v, []).append((i % w, i // w))
    if len(groups) != len(pieces):
        return False
    for idx, cells in groups.items():
        want = tuple(sorted(tuple(c) for c in pieces[idx]))
        if len(cells) != 4 or _normalize(cells) != want:
            return False
    return True


# ── nonogram (picross 5×5) ───────────────────────────────────────────────────
def _clues(line) -> list[int]:
    out, run = [], 0
    for v in line:
        if v:
            run += 1
        elif run:
            out.append(run)
            run = 0
    if run:
        out.append(run)
    return out or [0]


def gen_nonogram(rng: random.Random, n: int = 5, givens: int = 2) -> dict:
    while True:
        grid = [1 if rng.random() < 0.55 else 0 for _ in range(n * n)]
        filled = sum(grid)
        if n + 2 <= filled <= n * n - 3:            # not trivial, not full
            break
    rows = [_clues(grid[r * n:(r + 1) * n]) for r in range(n)]
    cols = [_clues(grid[c::n]) for c in range(n)]
    # `givens` cells come pre-painted — a toe-hold. The puzzle isles and the
    # MAGIC picross set this differently (STRIKE gets 5, MAGIC gets 0).
    filled_idx = [i for i, v in enumerate(grid) if v]
    given = sorted(rng.sample(filled_idx, min(max(0, givens), len(filled_idx))))
    return {"n": n, "rows": rows, "cols": cols, "given": given, "secret": {}}


def check_nonogram(data: dict, grid) -> bool:
    n = data["n"]
    if not isinstance(grid, list) or len(grid) != n * n:
        return False
    if any(v not in (0, 1) for v in grid):
        return False
    rows = [_clues(grid[r * n:(r + 1) * n]) for r in range(n)]
    cols = [_clues(grid[c::n]) for c in range(n)]
    return rows == data["rows"] and cols == data["cols"]


# ── simon (memory sequence, starts at 6) ─────────────────────────────────────
def gen_simon(rng: random.Random, length: int = 6) -> dict:
    seq = []
    for _ in range(length):
        nxt = rng.randrange(9)
        while seq and nxt == seq[-1]:               # no immediate repeats
            nxt = rng.randrange(9)
        seq.append(nxt)
    # the sequence must be public — the client has to flash it
    return {"pad": 9, "seq": seq, "secret": {}}


def check_simon(data: dict, taps) -> bool:
    return isinstance(taps, list) and taps == data["seq"]


# ── memory (simon's little sibling: a 2×2 pad, only 4 to remember) ───────────
def gen_memory(rng: random.Random, length: int = 4) -> dict:
    seq = []
    for _ in range(length):
        nxt = rng.randrange(4)
        while seq and nxt == seq[-1]:               # no immediate repeats
            nxt = rng.randrange(4)
        seq.append(nxt)
    return {"pad": 4, "seq": seq, "secret": {}}     # pad 4 → a 2×2 board


# ── visual memory (Human Benchmark): flash tiles, then click them back ───────
def gen_visual_memory(rng: random.Random, n: int = 6,
                      lit: int | None = None) -> dict:
    """An n×n board briefly flashes `lit` tiles; memorise them, then click them
    all back. THREE misses (lives) and it's lost. The flashed set is PUBLIC —
    the client has to light it — exactly like simon's sequence; the checker just
    verifies the picks match it. One clean round wins the trial. About a THIRD of
    the board lights (the Human-Benchmark density): ~8 tiles on a 5×5, 11 on a
    6×6, 15 on a 7×7."""
    if lit is None:
        lit = max(4, round(n * n * 0.3))
    lit = min(lit, n * n)
    cells = sorted(rng.sample(range(n * n), lit))
    return {"n": n, "flash": cells, "lives": 3, "secret": {}}


def check_visual_memory(data: dict, picks) -> bool:
    """Pass only if EVERY flashed tile was found and no stray tile submitted —
    the client sends the set it uncovered when the board is cleared."""
    return isinstance(picks, list) and sorted(set(picks)) == data["flash"]


# ── anagram unscramble ───────────────────────────────────────────────────────
def gen_anagram(rng: random.Random) -> dict:
    word = rng.choice(WORDS)
    letters = list(word)
    for _ in range(20):
        rng.shuffle(letters)
        if "".join(letters) != word:
            break
    return {"letters": "".join(letters), "length": len(word),
            "secret": {"word": word}}


def check_anagram(data: dict, guess) -> bool:
    if not isinstance(guess, str):
        return False
    guess = guess.strip().upper()
    word = data["secret"]["word"]
    if guess == word:
        return True
    # any real word from our list using exactly these letters also counts
    return sorted(guess) == sorted(word) and guess in _WORD_SET


# ── raven's matrix ───────────────────────────────────────────────────────────
_SHAPES = ["circle", "square", "triangle", "diamond"]
_FILLS = ["empty", "half", "full"]


def _rule(rng: random.Random, values: list):
    """Returns f(row, col) -> value; one of three systematic rules."""
    vals = values[:]
    rng.shuffle(vals)
    vals = vals[:3]
    mode = rng.choice(["row", "col", "latin"])
    if mode == "row":
        return lambda r, c: vals[r]
    if mode == "col":
        return lambda r, c: vals[c]
    return lambda r, c: vals[(r + c) % 3]


def gen_ravens(rng: random.Random) -> dict:
    shape_of = _rule(rng, _SHAPES)
    count_of = _rule(rng, [1, 2, 3])
    fill_of = _rule(rng, _FILLS)
    glyph = lambda r, c: {"shape": shape_of(r, c), "count": count_of(r, c),
                          "fill": fill_of(r, c)}
    grid = [glyph(r, c) for r in range(3) for c in range(3)]
    answer = grid[8]
    shown = grid[:8]

    def mutate(g):
        m = dict(g)
        attr = rng.choice(["shape", "count", "fill"])
        if attr == "shape":
            m["shape"] = rng.choice([s for s in _SHAPES if s != g["shape"]])
        elif attr == "count":
            m["count"] = rng.choice([n for n in (1, 2, 3, 4) if n != g["count"]])
        else:
            m["fill"] = rng.choice([f for f in _FILLS if f != g["fill"]])
        return m

    options = [answer]
    guard = 0
    while len(options) < 4 and guard < 200:
        guard += 1
        cand = mutate(answer)
        if rng.random() < 0.4:
            cand = mutate(cand)
        if cand not in options:
            options.append(cand)
    rng.shuffle(options)
    return {"grid": shown, "options": options,
            "secret": {"correct": options.index(answer)}}


def check_ravens(data: dict, idx) -> bool:
    return isinstance(idx, int) and idx == data["secret"]["correct"]


