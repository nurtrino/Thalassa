"""
Puzzle isles — failable, time-limited brain challenges.

Five kinds. Three are INTERACTIVE MINIGAMES, generated fresh every time and
validated server-side (the client never receives a solution):

  · sliding    3×3 eight-puzzle — scrambled by legal moves, so always solvable
  · lightsout  4×4 toggle grid — generated by pressing from solved, so always solvable
  · tetromino  fill a 4×5 region exactly with 5 tetromino pieces — generated by
               actually tiling the region first, so always solvable

Two are timed multiple-choice:

  · sequence   generated "what comes next?" number/letter patterns (infinite)
  · riddle     ★ PLACEHOLDER hand-written brain teasers — replace with your own.
               Good sources: Project Gutenberg (Sam Loyd's "Cyclopedia of
               Puzzles", Dudeney's "Amusements in Mathematics" — public domain),
               Martin Gardner / Raymond Smullyan collections, Puzzling
               StackExchange (CC BY-SA, keep attribution), MindYourDecisions,
               NPR Sunday Puzzle, Mensa/GCHQ puzzle books.

Riddle format: {"text": ..., "options": [4 strings], "correct": one of them}.
"""
