"""
Puzzle isles — failable, time-limited brain challenges.

Five interactive/generated kinds (client never receives fields in "secret"):

  · tetromino  Talos-Principle-style sigil fill: drag the given pieces to
               tile the region exactly (a quick 4×4 in STRIKE combat, the full
               6×6 on isles and in MAGIC). NO rotation — each piece comes in the
               orientation it must be placed. Generated by tiling the region
               first, so always solvable; placed pieces can be dragged to move.
  · nonogram   5×5 picross against a 30s clock: paint cells to satisfy
               row/column clues. Just TWO cells come pre-filled ("given"
               cells, locked in the client). Any grid matching the clues counts.
  · simon      memory: watch a flashed sequence on a 3×3 pad, then reproduce
               it (4 tones in a STRIKE-vs-pack fight, 6 elsewhere).
  · visual_memory  Human-Benchmark recall: a 6×6 board flashes a set of tiles;
               memorise them, then click them all back. Three misses (lives)
               ends it. The flashed set is public (the client lights it), like
               simon's sequence — the checker just verifies the picks.
  · anagram    unscramble a themed word (typed answer).
  · ravens     Raven's-matrix: 3×3 glyph grid follows hidden row/col rules;
               pick the missing ninth tile.
  · sequence   "The Fates' Thread": a number sequence from a random rule
               (arith/geo/fib/squares/primes/triangular/cubes) — type the next
               term. The answer rides in "secret".
  · lights_out "The Gorgon's Gaze": a 4×4 grid; tapping a cell toggles it and
               its orthogonal neighbours — extinguish every light. Scrambled
               from all-off, so always solvable by replaying taps.
  · sliding    "The Shifting Mosaic": a 3×3 sliding-tile puzzle (0 = blank),
               scrambled from the solved goal with legal moves (always
               solvable); restore the goal order.

Plus "riddle" — a typed-answer brain teaser (like anagram, an INTERACTIVE
minigame): the player reads a themed riddle and types the answer against a 30s
clock. The answer rides in "secret"; the checker normalizes case, whitespace,
leading articles and punctuation, and accepts spelling variants. Content lives
in riddles_typed.RIDDLES (50 riddles across 5 THALASSA themes).
"""
